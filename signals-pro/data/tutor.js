function norm(s) {
  return String(s || '')
    .replace(/[\uff01-\uff5e]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0))
    .toLowerCase()
    .replace(/\s+/g, '');
}

function match(q) {
  const t = norm(q);
  if (!t) return null;
  let best = null;
  let bestScore = 0;
  THEMES.forEach((theme) => {
    let score = 0;
    if (norm(theme.title) && t.indexOf(norm(theme.title)) >= 0) score += 6;
    theme.keys.forEach((k) => {
      const nk = norm(k);
      if (nk && t.indexOf(nk) >= 0) score += nk.length >= 3 ? 4 : 2;
    });
    if (score > bestScore) {
      bestScore = score;
      best = theme;
    }
  });
  return bestScore >= 2 ? best : null;
}

// 按讲解方式拼装回复块
function compose(theme, mode) {
  if (!theme) return null;
  const blocks = [];
  if (mode === 'derive') {
    blocks.push({ type: 'p', text: '按定义一步步推，关键是把"为什么"讲清楚：' });
    theme.derive.forEach((s, i) => blocks.push({ type: 'step', index: i + 1, text: s }));
    blocks.push({ type: 'formula', ids: theme.formulas.slice(0, 2) });
  } else if (mode === 'example') {
    blocks.push({ type: 'p', text: '来看一道典型题：' });
    blocks.push({ type: 'quote', text: theme.example.stem });
    theme.example.steps.forEach((s, i) => blocks.push({ type: 'step', index: i + 1, text: s }));
    blocks.push({ type: 'answer', text: theme.example.answer });
    blocks.push({ type: 'formula', ids: theme.formulas.slice(0, 1) });
  } else if (mode === 'method') {
    blocks.push({ type: 'p', text: '做这类题的固定套路：' });
    theme.method.forEach((s, i) => blocks.push({ type: 'step', index: i + 1, text: s }));
    blocks.push({ type: 'tip', text: theme.tip });
  } else if (mode === 'chat') {
    blocks.push({ type: 'p', text: theme.concept[0] });
    if (theme.concept[1]) blocks.push({ type: 'p', text: theme.concept[1] });
    blocks.push({ type: 'tip', text: theme.tip });
    blocks.push({ type: 'formula', ids: theme.formulas.slice(0, 2) });
  } else {
    theme.concept.forEach((p) => blocks.push({ type: 'p', text: p }));
    blocks.push({ type: 'tip', text: theme.tip });
    blocks.push({ type: 'formula', ids: theme.formulas.slice(0, 2) });
  }
  return { title: theme.title, blocks };
}

